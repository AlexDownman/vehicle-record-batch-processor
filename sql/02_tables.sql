-- 02_tables.sql
-- Creates the core tables: VEHICLES, KEEPERS, BATCH_RUNS and REJECTIONS.
--
-- Run as VSS, connected to the PDB:
--   docker/oracle.sh sqlplus vss@FREEPDB1 @/sql/02_tables.sql
--
-- WARNING: drops and recreates the tables, so all vehicle, keeper and batch
-- history is lost. This is a setup script, not something the batch runs.
--
-- Oracle does not index foreign key columns automatically (unlike MySQL).
-- An unindexed foreign key makes deletes on the parent table slow and can
-- lock the whole child table, so every foreign key below has an index.

WHENEVER SQLERROR EXIT SQL.SQLCODE

-- Children before parents, or the foreign keys block the drop.
DROP TABLE IF EXISTS rejections PURGE;
DROP TABLE IF EXISTS keepers    PURGE;
DROP TABLE IF EXISTS vehicles   PURGE;
DROP TABLE IF EXISTS batch_runs PURGE;

-- ---------------------------------------------------------------------------
-- BATCH_RUNS: one row per nightly run, for bookkeeping and the report.
-- ---------------------------------------------------------------------------
-- GENERATED ALWAYS AS IDENTITY is Oracle's auto-increment: the database
-- assigns the next number and rejects any attempt to supply one.
CREATE TABLE batch_runs (
    batch_run_id      NUMBER        GENERATED ALWAYS AS IDENTITY
                                    CONSTRAINT batch_runs_pk PRIMARY KEY,
    file_name         VARCHAR2(100) CONSTRAINT batch_runs_file_nn NOT NULL,
    started_at        TIMESTAMP     DEFAULT SYSTIMESTAMP
                                    CONSTRAINT batch_runs_started_nn NOT NULL,
    finished_at       TIMESTAMP,
    status            VARCHAR2(10)  DEFAULT 'RUNNING'
                                    CONSTRAINT batch_runs_status_nn NOT NULL,
    records_read      NUMBER(9)     DEFAULT 0 CONSTRAINT batch_runs_read_nn     NOT NULL,
    records_applied   NUMBER(9)     DEFAULT 0 CONSTRAINT batch_runs_applied_nn  NOT NULL,
    records_rejected  NUMBER(9)     DEFAULT 0 CONSTRAINT batch_runs_rejected_nn NOT NULL,
    CONSTRAINT batch_runs_status_ck
        CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    -- A finished run must say when it finished; a running one must not.
    CONSTRAINT batch_runs_finished_ck
        CHECK ((status = 'RUNNING' AND finished_at IS NULL)
            OR (status <> 'RUNNING' AND finished_at IS NOT NULL))
);

CREATE INDEX batch_runs_file_ix ON batch_runs (file_name);

COMMENT ON TABLE batch_runs IS 'One row per nightly batch run';

-- ---------------------------------------------------------------------------
-- VEHICLES: one row per vehicle, seeded from MOT_STAGING.
-- ---------------------------------------------------------------------------
CREATE TABLE vehicles (
    vehicle_id         NUMBER(12)    CONSTRAINT vehicles_pk PRIMARY KEY,
    registration       VARCHAR2(8)   CONSTRAINT vehicles_reg_nn NOT NULL,
    make               VARCHAR2(50)  CONSTRAINT vehicles_make_nn NOT NULL,
    model              VARCHAR2(50)  CONSTRAINT vehicles_model_nn NOT NULL,
    colour             VARCHAR2(20)  CONSTRAINT vehicles_colour_nn NOT NULL,
    fuel_type          VARCHAR2(30),
    cylinder_capacity  NUMBER(6),
    first_use_date     DATE          CONSTRAINT vehicles_first_use_nn NOT NULL,
    latest_mileage     NUMBER(9),
    status             VARCHAR2(8)   DEFAULT 'ACTIVE'
                                     CONSTRAINT vehicles_status_nn NOT NULL,
    scrapped_date      DATE,
    last_updated       TIMESTAMP     DEFAULT SYSTIMESTAMP
                                     CONSTRAINT vehicles_updated_nn NOT NULL,
    last_batch_run_id  NUMBER        CONSTRAINT vehicles_batch_run_fk
                                     REFERENCES batch_runs (batch_run_id),
    CONSTRAINT vehicles_reg_uk UNIQUE (registration),
    -- Current UK format: two letters, two-digit age identifier, space,
    -- three letters (e.g. AB12 CDE).
    CONSTRAINT vehicles_reg_format_ck
        CHECK (REGEXP_LIKE(registration, '^[A-Z]{2}[0-9]{2} [A-Z]{3}$')),
    CONSTRAINT vehicles_status_ck
        CHECK (status IN ('ACTIVE', 'SCRAPPED')),
    -- Scrapped vehicles must have a scrap date; active ones must not.
    CONSTRAINT vehicles_scrapped_ck
        CHECK ((status = 'ACTIVE'   AND scrapped_date IS NULL)
            OR (status = 'SCRAPPED' AND scrapped_date IS NOT NULL))
);

CREATE INDEX vehicles_batch_run_ix ON vehicles (last_batch_run_id);

COMMENT ON TABLE  vehicles                   IS 'Vehicle record of truth; one row per DVSA vehicle_id';
COMMENT ON COLUMN vehicles.registration      IS 'Synthetic UK registration, generated by sql/04_seed_vehicles.sql';
COMMENT ON COLUMN vehicles.last_batch_run_id IS 'Batch run that last changed this row; NULL if unchanged since seeding';

-- ---------------------------------------------------------------------------
-- KEEPERS: keeper history. All names and postcodes are synthetic (Faker).
-- ---------------------------------------------------------------------------
-- A keeper change ends the current row (sets end_date) and inserts a new
-- one, so the history is kept rather than overwritten.
CREATE TABLE keepers (
    keeper_id    NUMBER        GENERATED ALWAYS AS IDENTITY
                               CONSTRAINT keepers_pk PRIMARY KEY,
    vehicle_id   NUMBER(12)    CONSTRAINT keepers_vehicle_nn NOT NULL
                               CONSTRAINT keepers_vehicle_fk
                               REFERENCES vehicles (vehicle_id),
    keeper_name  VARCHAR2(40)  CONSTRAINT keepers_name_nn NOT NULL,
    postcode     VARCHAR2(8)   CONSTRAINT keepers_postcode_nn NOT NULL,
    start_date   DATE          CONSTRAINT keepers_start_nn NOT NULL,
    end_date     DATE,
    -- Outward code (1-2 letters, a digit, optional letter or digit), space,
    -- inward code (a digit, two letters). E.g. SA1 1AA, SW1A 2AA.
    CONSTRAINT keepers_postcode_ck
        CHECK (REGEXP_LIKE(postcode, '^[A-Z]{1,2}[0-9][A-Z0-9]? [0-9][A-Z]{2}$')),
    CONSTRAINT keepers_dates_ck
        CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX keepers_vehicle_ix ON keepers (vehicle_id);

-- At most one current keeper per vehicle. This is a function-based index:
-- the CASE gives vehicle_id for current rows and NULL for ended ones.
-- Oracle does not store all-NULL keys in an index, so only current
-- keepers take part in the uniqueness check.
CREATE UNIQUE INDEX keepers_one_current_uk
    ON keepers (CASE WHEN end_date IS NULL THEN vehicle_id END);

COMMENT ON TABLE keepers IS 'Registered keeper history; synthetic data only, never real personal data';

-- ---------------------------------------------------------------------------
-- REJECTIONS: every record the batch refused, with the reason.
-- ---------------------------------------------------------------------------
CREATE TABLE rejections (
    rejection_id  NUMBER         GENERATED ALWAYS AS IDENTITY
                                 CONSTRAINT rejections_pk PRIMARY KEY,
    batch_run_id  NUMBER         CONSTRAINT rejections_batch_run_nn NOT NULL
                                 CONSTRAINT rejections_batch_run_fk
                                 REFERENCES batch_runs (batch_run_id),
    line_number   NUMBER(9)      CONSTRAINT rejections_line_nn NOT NULL,
    stage         VARCHAR2(10)   CONSTRAINT rejections_stage_nn NOT NULL,
    reason_code   VARCHAR2(30)   CONSTRAINT rejections_reason_nn NOT NULL,
    reason_text   VARCHAR2(200),
    registration  VARCHAR2(8),
    change_type   VARCHAR2(8),
    raw_record    VARCHAR2(100),
    rejected_at   TIMESTAMP      DEFAULT SYSTIMESTAMP
                                 CONSTRAINT rejections_at_nn NOT NULL,
    -- VALIDATOR = structural fault caught by the C validator,
    -- PLSQL     = business rule failed in vehicle_batch_pkg.
    -- (No semicolon at the end of a comment line: SQL*Plus would take it
    -- as the end of the statement.)
    CONSTRAINT rejections_stage_ck
        CHECK (stage IN ('VALIDATOR', 'PLSQL')),
    -- A line of the inbound file can only be rejected once per run.
    -- This unique constraint's index also serves the foreign key.
    CONSTRAINT rejections_line_uk UNIQUE (batch_run_id, line_number)
);

COMMENT ON TABLE rejections IS 'Records rejected by a batch run, with the stage and reason';

PROMPT Tables BATCH_RUNS, VEHICLES, KEEPERS and REJECTIONS created.
EXIT
